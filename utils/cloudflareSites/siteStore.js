// utils/cloudflareSites/siteStore.js
//
// What a published website needs kept so it can be rendered again.
//
//   capture(distDir, siteId)   at publish time
//   restoreAssets(siteId, distDir)  before a re-render
//   forget(siteId)             when the site is deleted
//
// THREE THINGS, IN TWO PLACES, AND THE SPLIT IS DELIBERATE
//
//   content.json   the site's words          -> Mongo, on the row
//   build.json     what the wizard was asked -> Mongo, on the row
//   assets/        the images                -> disk, builds/sites/<id>/
//
// The first two are small JSON and belong with the record they describe. The
// images are ~700 KB a site and belong nowhere near a 512 MB database.
//
//
// WHY THE IMAGES ARE KEPT AT ALL, SINCE THE EDIT NEVER TOUCHES THEM
//
// Editing changes words. It does not change `src="assets/hero-1.webp"`, and
// nothing here rewrites a path. But a re-render writes a FRESH
// dist/user_<id>, and `wrangler pages deploy` ships a DIRECTORY as the whole
// site — a file absent from the folder is absent from the deployment.
//
//     THE PATHS STAYING CORRECT IS NOT THE SAME AS THE FILES BEING THERE.
//     Without this, an edit publishes a site whose <img> tags are all right
//     and all 404.
//
// dist/user_<id> is one folder per user and the next build wipes it, so the
// images cannot simply be left where they were.
//
//
// WHY NOT FETCH THEM BACK FROM CLOUDFLARE
//
// It was considered and measured. The published site serves them at known
// URLs, so a re-render could pull them down and store nothing at all — but
// the file list would have to come from somewhere, and the model is not it:
// a real build had 25 files in assets/ and recorded 23. The two missing ones
// were the hero trust badges, which are rendered into the pages and never
// stored as image srcs.
//
// Scraping the published HTML would find them. It would also make every edit
// depend on the live site being up, correct and finished deploying — and if
// a bad deploy ever went out, the next re-render would faithfully copy it
// back. A folder copy cannot miss a file and cannot inherit a mistake.
//
// Edwin, 7 November: "save it on disk".

'use strict';

const fs = require('fs');
const fsp = require('fs/promises');
const path = require('path');

const CM = require('../contentModel');
const { readRecipe } = require('../buildRecipe');

/** Beside builds/zips/, which is the same kind of thing for the same reason. */
const DEFAULT_ROOT = path.join(__dirname, '..', '..', 'builds', 'sites');

/**
 * Where kept files live, read at CALL time rather than captured at load.
 *
 * AN ENVIRONMENT VARIABLE, NOT A TEST-ONLY SETTER, and it earned the
 * distinction: the first version of this file exported `STORE_ROOT` as a
 * const and test-site-store.js reassigned `siteStore.STORE_ROOT` to a temp
 * folder, believing it had redirected the module. It had not — dirFor()
 * closed over the const, so every test in that suite wrote into the real
 * builds/sites/. The suite still passed fifteen of sixteen.
 *
 *     A CONST CAPTURED AT LOAD CANNOT BE REDIRECTED BY ASSIGNING
 *     TO THE EXPORT THAT LOOKS LIKE IT.
 *
 * Read per call, the override works for tests and is also the thing a server
 * needs the day these belong on a different disk than the code.
 */
function storeRoot() {
  return process.env.SITE_STORE_ROOT || DEFAULT_ROOT;
}

/** The only sub-folder kept. css and js are regenerated by every build. */
const ASSETS = 'assets';

/**
 * Where a Local Website Options build keeps its words.
 *
 * THE SECOND SHAPE, AND IT IS NOT A SECOND content.json. runLocalOptions.js
 * says why it refuses that filename: utils/contentModel.js owns it, it is
 * the WordPress exporter's format, and writing a different shape to the same
 * path would be a file that lies about what it describes.
 *
 * WHICH IS WHY EVERY LOCAL WEBSITE OPTIONS SITE HAS BEEN UNEDITABLE SINCE
 * THE EDIT SCREEN SHIPPED. capture() read content.json, found none, and
 * returned `ok: false` — so `editable` was false, the button never drew, and
 * nothing anywhere said why. Seven sites went live on 18 November before
 * anybody noticed, and the screen that explains it can only be reached by
 * typing its URL.
 *
 *     A FUNCTION THAT HANDLES ONE OF TWO FORMATS AND REPORTS
 *     "NO CONTENT" FOR THE OTHER IS NOT MISSING A FEATURE.
 *     IT IS WRONG ABOUT WHAT IT WAS GIVEN.
 *
 * COPIED, NOT IMPORTED, AND test-site-store.js HOLDS THE TWO TOGETHER.
 * runLocalOptions.js exports SOURCE_PATH, but it is the generator: eleven
 * hundred lines that reach the model, the credit ledger and Cloudflare.
 * This module is required by the publish path and by tests that have no
 * business loading any of that. One string is cheaper to assert than a
 * dependency is to carry.
 */
const LOCAL_OPTIONS_PATH = path.join('_src', 'localoptions.json');

/**
 * Whether a stored model is a Local Website Options source.
 *
 * ONE READING, BECAUSE THERE ARE THREE CALLERS. capture() decides whether it
 * found something usable, the route decides whether to draw the button, and
 * the rebuild decides which renderer to run. whyNotEditable() already carries
 * the note about what two readings of the same fields cost — a screen that
 * offers a button the handler behind it refuses — and this is the same risk
 * one layer down.
 *
 * IT ASKS THE DATA, NOT A COLUMN BESIDE IT. `sourceOf()` stamps
 * `mode: 'localoptions'` into the file itself, so the stored words say what
 * they are. A field on the row would be a second place for the same fact,
 * set at capture time and wrong for every site captured before it existed.
 */
function isLocalOptions(model) {
  return Boolean(model) && 'localoptions' === model.mode;
}

/**
 * Where one site's kept files live.
 *
 * THE ID IS CHECKED, NOT INTERPOLATED. It is a Mongo ObjectId today and
 * therefore hex — but this builds a filesystem path out of it, and a path
 * built from an identifier is a traversal the first time that identifier
 * comes from somewhere else. `../../etc` is a string too.
 */
function dirFor(siteId) {
  const id = String(siteId || '');

  if (!/^[a-f0-9]{24}$/i.test(id)) {
    throw new Error(`Refusing to build a store path from "${id}"`);
  }

  return path.join(storeRoot(), id);
}

/**
 * Copy one folder's files into another, creating it if needed.
 *
 * FLAT, NOT RECURSIVE. assets/ has no sub-folders in any build this has
 * seen, and a recursive copy here would be code with no test behind it —
 * the kind this codebase has removed before. A sub-folder appearing is
 * reported rather than silently skipped.
 */
async function copyFlat(from, to) {
  await fsp.mkdir(to, { recursive: true });

  const entries = await fsp.readdir(from, { withFileTypes: true });

  let files = 0;
  let bytes = 0;
  const skipped = [];

  for (const entry of entries) {
    if (!entry.isFile()) { skipped.push(entry.name); continue; }

    const src = path.join(from, entry.name);
    const dest = path.join(to, entry.name);

    await fsp.copyFile(src, dest);

    files += 1;
    bytes += (await fsp.stat(dest)).size;
  }

  return { files, bytes, skipped };
}

/**
 * Read a Local Website Options build's stored source, or null.
 *
 * SAME FAILURE SHAPE AS CM.readModel() — null for absent, null for
 * unreadable, and it says which on the way past. The caller cannot act
 * differently on the two: a build with no source and a build with a source
 * nobody can parse are both builds that cannot be re-rendered.
 *
 * AND IT CHECKS THE MODE RATHER THAN TRUSTING THE PATH. A file at that name
 * holding something else is not a Local Website Options source, and treating
 * it as one would hand renderSite() an object it has never seen.
 */
function readLocalOptions(distDir) {
  try {
    const target = path.join(distDir, LOCAL_OPTIONS_PATH);

    if (!fs.existsSync(target)) return null;

    const parsed = JSON.parse(fs.readFileSync(target, 'utf8'));

    return isLocalOptions(parsed) ? parsed : null;
  } catch (err) {
    console.error('⚠️ Could not read localoptions.json:', err.message);
    return null;
  }
}

/**
 * Keep what this build needs to be rendered again.
 *
 * @returns {{ok: true, model, recipe, assets:{files,bytes,skipped}}}
 *        | {{ok: false, error}}
 *
 * THE MODEL IS REQUIRED AND THE REST IS NOT, which is the one judgement in
 * this function. Without words there is nothing to edit, so capturing would
 * store a record that promises an edit screen it cannot fill. Without
 * build.json or the images, an edit regenerates — expensive, not broken.
 *
 * TWO FORMATS, AND THE SECOND ONE NEEDS NO RECIPE. For a generator build the
 * model is the words and the recipe is the decisions, and a re-render from
 * one without the other builds a site from half an answer. A Local Website
 * Options source is BOTH: `renderSite(stored)` is the whole re-render, which
 * is why generate.js stores the same object it rendered from rather than a
 * copy of its interesting parts. So `recipe` stays null for one and that is
 * not a gap — see isLocalOptions() above, and the editable check in
 * routes/cloudflareSitesRoute.js which asks this module rather than counting
 * fields itself.
 */
async function capture(distDir, siteId) {
  const model = CM.readModel(distDir) || readLocalOptions(distDir);

  if (!model) {
    return {
      ok: false,
      error: 'That build has no content.json and no localoptions.json, so it '
           + 'cannot be edited later. It was published; it just cannot be '
           + 're-rendered without generating the words again.',
    };
  }

  /* NOT ASKED FOR AT ALL ON THE SECOND PATH, rather than asked for and
   * ignored. readRecipe() reads _src/build.json, which this mode does not
   * write; calling it would log a miss on every Local Website Options
   * publish and teach whoever read the log to expect a file that is not
   * coming. */
  const recipe = isLocalOptions(model) ? null : readRecipe(distDir);

  let assets = { files: 0, bytes: 0, skipped: [] };

  const from = path.join(distDir, ASSETS);

  if (fs.existsSync(from)) {
    /* REPLACED, NOT MERGED. A site re-published after its images changed
     * would otherwise keep both sets, and the stale ones would go back up on
     * the next re-render under names nothing references — growing the folder
     * and the deploy for ever. */
    const to = path.join(dirFor(siteId), ASSETS);
    await fsp.rm(to, { recursive: true, force: true });

    assets = await copyFlat(from, to);
  }

  return { ok: true, model, recipe, assets };
}

/**
 * Put the kept images back into a freshly built folder.
 *
 * CALLED BEFORE THE RE-RENDER, NOT AFTER. runGeneration wipes and refills
 * dist/user_<id>, so anything copied in beforehand is gone. It writes the
 * images it has — predefined ones it can copy itself, uploads it cannot —
 * and then this fills the gaps.
 *
 * COPIES WITHOUT OVERWRITING. A re-render that produced its own copy of an
 * image produced it from the same source; a stored copy written over the top
 * would be the same bytes at best and a stale version at worst.
 *
 * @returns {{restored:number, skipped:number, had:boolean}}
 */
async function restoreAssets(siteId, distDir) {
  const from = path.join(dirFor(siteId), ASSETS);

  if (!fs.existsSync(from)) return { restored: 0, skipped: 0, had: false };

  const to = path.join(distDir, ASSETS);
  await fsp.mkdir(to, { recursive: true });

  const entries = await fsp.readdir(from, { withFileTypes: true });

  let restored = 0;
  let skipped = 0;

  for (const entry of entries) {
    if (!entry.isFile()) continue;

    const dest = path.join(to, entry.name);

    if (fs.existsSync(dest)) { skipped += 1; continue; }

    await fsp.copyFile(path.join(from, entry.name), dest);
    restored += 1;
  }

  return { restored, skipped, had: true };
}

/**
 * Drop one site's kept files.
 *
 * NOT FATAL, EVER. This runs when a site is deleted, and a folder that will
 * not go is worth a line in the log and nothing more — the alternative is a
 * website the customer cannot delete because of a disk they cannot see.
 */
async function forget(siteId) {
  try {
    await fsp.rm(dirFor(siteId), { recursive: true, force: true });
    return { ok: true };
  } catch (err) {
    return { ok: false, error: err.message };
  }
}

/** For the admin screen, and for anybody asking what this costs. */
async function sizeOf(siteId) {
  const dir = path.join(dirFor(siteId), ASSETS);
  if (!fs.existsSync(dir)) return { files: 0, bytes: 0 };

  const entries = await fsp.readdir(dir, { withFileTypes: true });

  let files = 0;
  let bytes = 0;

  for (const entry of entries) {
    if (!entry.isFile()) continue;
    files += 1;
    bytes += (await fsp.stat(path.join(dir, entry.name))).size;
  }

  return { files, bytes };
}

module.exports = {
  capture, restoreAssets, forget, sizeOf, dirFor, copyFlat, storeRoot,
  DEFAULT_ROOT, ASSETS,

  /* EXPORTED SO NOBODY WRITES `model.mode === 'localoptions'` AGAIN.
   * Three callers ask this question and the string is easy to type from
   * memory in a fourth place — which is how one of them ends up asking it
   * of `site.mode` or `recipe.mode` and being quietly always false. */
  isLocalOptions, readLocalOptions, LOCAL_OPTIONS_PATH,
};
